SELECT A1.AUDITORIUM AS [Аудитория], 
    A1.AUDITORIUM_TYPE AS [Тип], 
    A1.AUDITORIUM_CAPACITY AS [Вместимость]
FROM AUDITORIUM AS A1
WHERE A1.AUDITORIUM_CAPACITY = (SELECT TOP(1) AUDITORIUM.AUDITORIUM_CAPACITY FROM AUDITORIUM WHERE AUDITORIUM.AUDITORIUM_TYPE = A1.AUDITORIUM_TYPE ORDER BY AUDITORIUM.AUDITORIUM_CAPACITY DESC)
ORDER BY A1.AUDITORIUM_CAPACITY DESC

