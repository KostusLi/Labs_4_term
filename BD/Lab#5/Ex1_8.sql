SELECT 
    IDSTUDENT, 
    NAME AS [ФИО], 
    BDAY AS [Дата рождения]
FROM STUDENT
WHERE DAY(BDAY) = ANY (
    SELECT DAY(BDAY) 
    FROM STUDENT 
    GROUP BY DAY(BDAY) 
    HAVING COUNT(*) > 1
);