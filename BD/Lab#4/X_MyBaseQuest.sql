Use X_MyBase

SELECT Подразделения.[Название подразделения], Списания.[Причина списания], Списания.[Дата списания]
FROM Списания inner join Подразделения
ON Списания.[ID Подразделения] = Подразделения.[ID Подразделения]


SELECT Подразделения.[Название подразделения], Списания.[Причина списания], Списания.[Дата списания]
FROM Списания inner join Подразделения
ON Списания.[ID Подразделения] = Подразделения.[ID Подразделения] AND Списания.[Причина списания] like N'%ан%'