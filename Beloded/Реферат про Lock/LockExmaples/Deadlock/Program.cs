using System;
using System.Threading;
using System.Threading.Tasks;

namespace DeadlockDemo
{
    class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("=== Демонстрация Дедлока из-за lock(this) ===\n");

            // 1. Создаем наш уязвимый класс
            var server = new VulnerableServer();

            // 2. Запускаем фоновую задачу, которая попытается выполнить внутреннюю работу.
            // Ставим небольшую задержку, чтобы Главный поток (хулиган) успел захватить замок первым.
            Task.Run(() =>
            {
                Thread.Sleep(500);
                server.ProcessData();
            });

            // 3. ПОВЕДЕНИЕ "ХУЛИГАНА" (Внешний код)
            // Мы берем и вешаем замок на весь объект server СНАРУЖИ!
            Console.WriteLine("Главный поток: Я внешний код, и я захватываю замок на весь объект!");
            lock (server)
            {
                Console.WriteLine("Главный поток: Замок захвачен. Имитирую долгую работу (сплю бесконечно)...\n");

                // Имитация того, что внешний код завис или делает что-то очень долгое
                Thread.Sleep(Timeout.Infinite);
            }

            Console.WriteLine("Эта строка никогда не выведется.");
        }
    }

    // ==========================================
    // Класс с архитектурной ошибкой (Нарушение SRP и инкапсуляции)
    // ==========================================
    public class VulnerableServer
    {
        public void ProcessData()
        {
            Console.WriteLine("Фоновый поток: Пытаюсь зайти в lock(this) для обработки данных...");

            // ❌ КРИТИЧЕСКАЯ ОШИБКА ЗДЕСЬ
            // Объект пытается заблокировать сам себя.
            // Но внешний код (в методе Main) УЖЕ заблокировал его!
            lock (this)
            {
                // Сюда программа никогда не попадет
                Console.WriteLine("Фоновый поток: Успешно зашел! Обрабатываю данные...");
            }
        }
    }
}